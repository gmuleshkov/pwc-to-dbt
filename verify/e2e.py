"""End-to-end check: convert -> dbt build on DuckDB -> compare with dbt-labs/jaffle-shop.

Steps (all idempotent):
  1. Build the reference: clone jaffle-shop at a pinned commit, load its seeds (schema raw) and
     run its models (schema reference).
  2. Convert the ORIGINAL export, dbt build into schema `converted`, compare with the reference.
     Every difference must be listed, with its cause, in reference_map.toml [expected].
  3. Patch the diagnosed defects (repair_mapping.py), convert, dbt build into schema `repaired`,
     compare again ([expected_repaired]) and run the enriched-mart invariants.
  4. Write verify/REPORT.md. Exit 1 on any unexplained difference.

    uv run python verify/e2e.py            # or: make e2e
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
WORK = HERE / "work"
REFERENCE = HERE / "reference"
REFERENCE_REPO = "https://github.com/dbt-labs/jaffle-shop"
REFERENCE_SHA = "5beb145b00f5465ec759cfcdd9745e858818cf95"
SAMPLE = ROOT / "examples" / "FLOWLINE_DEMO_JAFFLESHOP.xml"
DB = WORK / "jaffle.duckdb"

sys.path.insert(0, str(HERE))
import compare  # noqa: E402
import invariants  # noqa: E402
import repair_mapping  # noqa: E402


def sh(*cmd: str, cwd: Path = ROOT, schema: str | None = None) -> None:
    env = dict(os.environ, PWC_DUCKDB_PATH=str(DB), DBT_PROFILES_DIR=str(HERE))
    if schema:
        env["PWC_SCHEMA"] = schema
    print("+", " ".join(cmd), flush=True)
    result = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)
    if result.returncode != 0:
        print(result.stdout[-4000:], result.stderr[-4000:], sep="\n")
        raise SystemExit(f"command failed: {' '.join(cmd)}")


def dbt(*args: str, cwd: Path, schema: str | None = None) -> None:
    sh(sys.executable, "-m", "dbt.cli.main", *args, cwd=cwd, schema=schema)


def reference_schema_ready() -> bool:
    if not DB.exists():
        return False
    import duckdb

    con = duckdb.connect(str(DB), read_only=True)
    try:
        n = con.execute("select count(*) from information_schema.tables where table_schema = 'reference'").fetchall()
        return n[0][0] >= 11
    finally:
        con.close()


def build_reference() -> None:
    if reference_schema_ready():
        print("reference: already built")
        return
    WORK.mkdir(parents=True, exist_ok=True)
    if not (REFERENCE / "dbt_project.yml").exists():
        REFERENCE.mkdir(parents=True, exist_ok=True)
        sh("git", "init", "-q", cwd=REFERENCE)
        sh("git", "fetch", "-q", "--depth", "1", REFERENCE_REPO, REFERENCE_SHA, cwd=REFERENCE)
        sh("git", "checkout", "-q", "FETCH_HEAD", cwd=REFERENCE)
    # jaffle-shop declares require-dbt-version >= 2.0; it runs fine on dbt-core 1.x with the check off.
    dbt("deps", "--no-version-check", cwd=REFERENCE)
    dbt("seed", "--no-version-check", "--full-refresh", "--vars", '{"load_source_data": true}', cwd=REFERENCE)
    dbt("run", "--no-version-check", cwd=REFERENCE)


def convert_and_build(xml: Path, project: Path, schema: str) -> None:
    sh(sys.executable, "-m", "pwc_to_dbt.cli", "convert", str(xml), "-o", str(project))
    dbt("build", cwd=project, schema=schema)


def main() -> int:
    build_reference()
    convert_and_build(SAMPLE, WORK / "converted_project", "converted")
    repaired = WORK / "repaired.xml"
    changes = repair_mapping.repair(str(SAMPLE), str(repaired))
    convert_and_build(repaired, WORK / "repaired_project", "repaired")

    original = compare.run(DB, schema="converted", expected_key="expected")
    fixed = compare.run(DB, schema="repaired", expected_key="expected_repaired")
    inv_fixed = invariants.run(DB, "repaired")
    inv_original = invariants.run(DB, "converted")

    parts = [
        "# End-to-end verification report",
        "",
        "Generated by `verify/e2e.py` (`make e2e`). Reference: "
        f"[dbt-labs/jaffle-shop@{REFERENCE_SHA[:7]}]({REFERENCE_REPO}/tree/{REFERENCE_SHA}) on DuckDB.",
        "",
        "Two runs:",
        "",
        "1. **Original export**: what PowerCenter would produce. Differences from jaffle-shop are "
        "expected where the mapping has a defect; each one is listed with its cause.",
        "2. **Repaired export**: the same export with the diagnosed defects patched "
        "(`verify/repair_mapping.py`). If the diagnosis and the converter are right, this matches "
        "jaffle-shop on every shared column.",
        "",
        "Patches applied for run 2:",
        "",
        *[f"- **{pid}** {desc}" for pid, desc in repair_mapping.PATCHES],
        "",
        "<details><summary>Exact changes</summary>\n",
        *[f"- {c}" for c in changes],
        "\n</details>",
        "",
        compare.report(original, "Run 1: original export vs reference", level=2),
        compare.report(fixed, "Run 2: repaired export vs reference", level=2),
        invariants.report(inv_fixed, "Run 2: invariants for the enriched marts (no jaffle-shop model to compare)"),
        invariants.report(inv_original, "Run 1: the same invariants on the original export (informational)"),
    ]
    text = "\n".join(parts)
    (HERE / "REPORT.md").write_text(text)
    bad = compare.failures(original) + compare.failures(fixed) + [k for k, v in inv_fixed.items() if v]
    print(f"wrote {HERE / 'REPORT.md'}")
    if bad:
        print("E2E FAILED:\n  " + "\n  ".join(bad), file=sys.stderr)
        return 1
    print("E2E OK: original-export differences all explained; repaired export matches the reference; "
          "enriched-mart invariants pass")
    return 0


if __name__ == "__main__":
    sys.exit(main())
