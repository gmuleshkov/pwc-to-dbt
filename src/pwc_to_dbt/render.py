"""Write a converted Project to disk as a dbt project, plus a conversion report."""

from __future__ import annotations

import json
import shutil
from collections import Counter
from pathlib import Path

from .convert import Project, column_sql_type, redact


def q(text: str) -> str:
    """YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(text)


def write_project(project: Project, out: Path, name: str, clean: bool = True) -> list[Path]:
    if clean and (out / "models").exists():
        shutil.rmtree(out / "models")
    out.mkdir(parents=True, exist_ok=True)
    written = [out / "dbt_project.yml"]
    written[0].write_text(dbt_project_yml(project, name))

    folders = sorted({m.folder.split("/")[0] for m in project.models})
    for model in project.models:
        path = out / "models" / model.folder / f"{model.name}.sql"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(model.sql)
        written.append(path)
    for folder in folders:
        path = out / "models" / folder / f"_{folder}__models.yml"
        path.write_text(models_yml([m for m in project.models if m.folder.split("/")[0] == folder]))
        written.append(path)
    if project.sources:
        path = out / "models" / "_sources.yml"
        path.write_text(sources_yml(project))
        written.append(path)
    report = out / "conversion_report.md"
    report.write_text(report_md(project))
    written.append(report)
    return written


def dbt_project_yml(project: Project, name: str) -> str:
    lines = [
        "# Generated by pwc-to-dbt.",
        f"name: {name}",
        "version: '1.0.0'",
        "config-version: 2",
        f"profile: {name}",
        "model-paths: ['models']",
        "",
    ]
    if project.vars:
        lines.append("vars:")
        for var, (default, comment) in sorted(project.vars.items()):
            lines.append(f"  {var}: {q(default)}  # {comment}")
        lines.append("")
    lines += [
        "models:",
        f"  {name}:",
        "    # PowerCenter sessions truncate and reload every target (Pre SQL TRUNCATE + insert),",
        "    # which is a full-refresh table in dbt.",
        "    +materialized: table",
    ]
    for folder in sorted({m.folder.split("/")[0] for m in project.models}):
        if any(m.kind == "intermediate" and m.folder.startswith(folder) for m in project.models):
            lines += [f"    {folder}:", "      intermediate:", "        +materialized: view"]
    return "\n".join(lines) + "\n"


def models_yml(models) -> str:
    lines = ["version: 2", "", "models:"]
    for m in models:
        lines += [f"  - name: {m.name}", f"    description: {q(m.description)}"]
        if m.columns:
            lines.append("    columns:")
            for c in m.columns:
                lines.append(f"      - name: {c.name}")
                if c.data_type:
                    lines.append(f"        data_type: {c.data_type}")
                if c.description:
                    lines.append(f"        description: {q(c.description)}")
                if c.tests:
                    lines.append("        data_tests:")
                    lines += [f"          - {t}" for t in c.tests]
    return "\n".join(lines) + "\n"


def sources_yml(project: Project) -> str:
    by_source: dict[str, list] = {}
    for st in project.sources.values():
        by_source.setdefault(st.source, []).append(st)
    lines = ["version: 2", "", "sources:"]
    for source, tables in sorted(by_source.items()):
        lines += [f"  - name: {source}", f"    schema: {source}",
                  f"    description: {q('Tables read by PowerCenter source definitions owned by ' + source.upper())}",
                  "    tables:"]
        for st in sorted(tables, key=lambda s: s.table.name):
            t = st.table
            lines.append(f"      - name: {t.name.lower()}")
            if t.description:
                lines.append(f"        description: {q(t.description)}")
            lines.append("        columns:")
            for c in t.columns:
                lines.append(f"          - name: {c.name.lower()}")
                sql_type = column_sql_type(c.datatype, c.precision, c.scale)
                if sql_type:
                    lines.append(f"            data_type: {sql_type}")
    return "\n".join(lines) + "\n"


def report_md(project: Project) -> str:
    f = project.folder
    out = ["# Conversion report", "", f"Folder `{f.name}`, mappings converted in run order: "
           + ", ".join(f"`{m}`" for m in project.mapping_names) + ".", ""]
    unsupported = [i for i in project.issues if i.level == "unsupported"]
    warnings = _dedupe([i for i in project.issues if i.level == "warning"])
    out += [f"- Models: {len(project.models)} "
            f"({sum(m.kind == 'target' for m in project.models)} targets, "
            f"{sum(m.kind == 'intermediate' for m in project.models)} shared intermediates)",
            f"- Unsupported constructs: {len(unsupported)} (those models fail at compile time on purpose)",
            f"- Warnings: {len(warnings)}", ""]

    out += ["## Models", "", "| Model | Mapping | From | Transformations |", "|---|---|---|---|"]
    for m in project.models:
        types = Counter(t for _, t in m.transformations if t not in ("TARGET",))
        out.append(f"| `{m.name}` | {m.mapping} | {m.instance} | "
                   + ", ".join(f"{t} x{c}" for t, c in types.most_common()) + " |")
    out.append("")
    if unsupported:
        out += ["## Unsupported (model generated as a compile error)", ""]
        out += [f"- **{i.mapping} / {i.instance}**: {i.message}" for i in unsupported] + [""]
    if warnings:
        out += ["## Warnings (review these: output may differ from PowerCenter or from intent)", ""]
        out += [f"- **{i.mapping} / {i.instance}**: {i.message}" for i in warnings] + [""]
    if project.vars:
        out += ["## Parameters", "", "Mapping variables became dbt vars (override with `--vars`):", ""]
        out += [f"- `{k}` default {v[0]!r} ({v[1]})" for k, v in sorted(project.vars.items())] + [""]
    out += ["## Not converted", ""]
    out.append("- Workflow and session settings: dbt's DAG (ref/source) replaces the run order; "
               "connections, schedules, recovery and pre/post SQL are not converted.")
    for wf in f.workflows:
        for t in wf.tasks:
            if t.type == "Command" and t.detail:
                out.append(f"- Command task `{t.name}` in workflow `{wf.name}` runs an external script "
                           f"(`{redact(t.detail)}`). Its SQL is not in the export; port it by hand "
                           "(for example as dbt models or an on-run-end hook).")
    for e in f.unsupported_elements:
        out.append(f"- `{e}`")
    return "\n".join(out) + "\n"


def _dedupe(issues):
    seen, out = set(), []
    for i in issues:
        key = (i.mapping, i.instance, i.message)
        if key not in seen:
            seen.add(key)
            out.append(i)
    return out
